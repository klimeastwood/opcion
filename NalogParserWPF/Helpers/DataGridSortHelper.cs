using System;
using System.Collections;
using System.Collections.Generic;
using System.Collections.Specialized;
using System.ComponentModel;
using System.Data;
using System.Linq;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Data;
using System.Windows.Threading;

namespace NalogParserWPF.Helpers
{
    /// <summary>
    /// Включает сортировку таблиц по клику на заголовок колонки.
    /// <para>
    /// У связанных колонок (<see cref="DataGridTextColumn"/>) путь сортировки известен WPF,
    /// а у шаблонных (<see cref="DataGridTemplateColumn"/>) его нет — колонки «Статус»,
    /// «Обновление», «Отметка» не сортировались вообще. Здесь путь выводится из шаблона ячейки
    /// (первая привязка текста) и подставляется в <see cref="DataGridColumn.SortMemberPath"/>.
    /// </para>
    /// <para>
    /// Путь всегда проверяется по фактическому источнику данных (свойство есть у элемента
    /// коллекции либо колонка есть в <see cref="DataView"/>), иначе колонка остаётся
    /// несортируемой: неверный путь приводит к исключению при первом клике по заголовку.
    /// </para>
    /// </summary>
    public static class DataGridSortHelper
    {
        /// <summary>Метка «колонки этой таблицы уже настроены» — защита от повторной подписки.</summary>
        private static readonly DependencyProperty AttachedProperty =
            DependencyProperty.RegisterAttached(
                "Attached",
                typeof(bool),
                typeof(DataGridSortHelper),
                new PropertyMetadata(false));

        /// <summary>Метка «исходный заголовок колонки уже запомнен» — защита от накопления стрелок.</summary>
        private static readonly DependencyProperty HeaderSavedProperty =
            DependencyProperty.RegisterAttached(
                "HeaderSaved",
                typeof(bool),
                typeof(DataGridSortHelper),
                new PropertyMetadata(false));

        /// <summary>Заголовок колонки таким, каким он задан в разметке (без стрелки сортировки).</summary>
        private static readonly DependencyProperty OriginalHeaderProperty =
            DependencyProperty.RegisterAttached(
                "OriginalHeader",
                typeof(object),
                typeof(DataGridSortHelper),
                new PropertyMetadata(null));

        /// <summary>Стрелка «по возрастанию» в заголовке отсортированной колонки.</summary>
        private const string AscendingArrow = " ▲";

        /// <summary>Стрелка «по убыванию» в заголовке отсортированной колонки.</summary>
        private const string DescendingArrow = " ▼";

        /// <summary>
        /// Подключает сортировку к таблице: разрешает сортировку по заголовку и размечает
        /// шаблонные колонки путём сортировки. Вызывается один раз при создании окна.
        /// </summary>
        /// <param name="grid">Таблица, для которой включается сортировка.</param>
        public static void AttachSorting(DataGrid? grid)
        {
            if (grid == null) return;
            if ((bool)grid.GetValue(AttachedProperty)) return;
            grid.SetValue(AttachedProperty, true);

            grid.CanUserSortColumns = true;
            ConfigureColumns(grid);

            // Колонки, сгенерированные из DataTable, появляются только после установки
            // ItemsSource, а шаблонные колонки можно разметить лишь по фактическим данным,
            // поэтому разметка повторяется по этим событиям.
            grid.AutoGeneratedColumns += (_, _) => ConfigureColumns(grid);
            grid.Loaded += (_, _) =>
            {
                ConfigureColumns(grid);
                UpdateSortArrows(grid);
            };
            if (grid.Items is INotifyCollectionChanged items)
                items.CollectionChanged += (_, _) => ConfigureColumns(grid);

            grid.Sorting += (_, e) =>
            {
                // Таблицы Белстата построены на DataView, который средствами WPF не сортируется:
                // путь колонки («[Территория Республики Беларусь]») читается как имя свойства,
                // и первый же клик по заголовку падает с «Тип "" не имеет свойства…». Поэтому
                // сортировка выполняется самим DataView (DataView.Sort), а событие помечается
                // выполненным — иначе WPF повторит свою (неудачную) попытку и покажет ошибку.
                if (grid.ItemsSource is DataView dataView && TryApplyDataViewSort(grid, dataView, e.Column))
                    e.Handled = true;

                // Направление сортировки выставляется уже после обработчика Sorting, поэтому
                // стрелка в заголовке обновляется отложенно — на следующем проходе диспетчера.
                grid.Dispatcher.BeginInvoke(
                    DispatcherPriority.Input,
                    new Action(() => UpdateSortArrows(grid)));
            };
        }

        /// <summary>
        /// Сортирует <see cref="DataView"/> по колонке, заголовок которой нажал пользователь.
        /// Направление чередуется (▲ → ▼ → ▲), сортировка с прежней колонки снимается,
        /// имя колонки экранируется индексными скобками («[г. Минск]») — только так
        /// <see cref="DataView.Sort"/> понимает имена измерений Белстата с точками и пробелами.
        /// </summary>
        /// <returns><c>true</c>, если имя колонки распознано и сортировка выполнена.</returns>
        private static bool TryApplyDataViewSort(DataGrid grid, DataView dataView, DataGridColumn column)
        {
            string? name = GetDataViewColumnName(column);
            if (string.IsNullOrEmpty(name) || dataView.Table == null || !dataView.Table.Columns.Contains(name))
                return false;

            // Имя с «]» в выражении DataView назвать нельзя: экранирование «]]» парсер выражений
            // не понимает, и DataView.Sort падал бы с SyntaxErrorException на первом же клике.
            // Такая колонка честно остаётся несортируемой (как и колонки без данных).
            if (name.Contains(']')) return false;

            var direction = column.SortDirection == ListSortDirection.Ascending
                ? ListSortDirection.Descending
                : ListSortDirection.Ascending;

            foreach (var other in grid.Columns)
            {
                if (!ReferenceEquals(other, column))
                    other.SortDirection = null;
            }

            column.SortDirection = direction;

            string reference = "[" + name + "]";
            dataView.Sort = reference + (direction == ListSortDirection.Ascending ? " ASC" : " DESC");
            return true;
        }

        /// <summary>
        /// Имя колонки <see cref="DataView"/> для колонки таблицы: берётся путь сортировки
        /// (либо путь привязки) и снимаются индексные скобки («[г. Минск]» → «г. Минск»).
        /// Заголовок не используется — помощник сам дописывает в него стрелку сортировки,
        /// и текст перестал бы совпадать с именем колонки.
        /// </summary>
        private static string? GetDataViewColumnName(DataGridColumn column)
        {
            string? path = null;

            if (!string.IsNullOrEmpty(column.SortMemberPath))
                path = column.SortMemberPath;
            else if (column is DataGridBoundColumn bound && bound.Binding is Binding binding)
                path = binding.Path?.Path;

            return string.IsNullOrWhiteSpace(path) ? null : UnwrapDataViewPath(path);
        }

        /// <summary>
        /// Показывает в заголовке колонки стрелку направления сортировки (▲ — по возрастанию,
        /// ▼ — по убыванию): по одному взгляду видно, по какой колонке отсортирована таблица.
        /// Исходный текст заголовка запоминается один раз, поэтому повторные сортировки
        /// не накапливают стрелки, а смена колонки убирает стрелку у прежней.
        /// </summary>
        private static void UpdateSortArrows(DataGrid grid)
        {
            foreach (var column in grid.Columns)
            {
                // Заголовки-элементы (иконки, разметка) не трогаем — их текст не строковый.
                if (column.Header is not string header) continue;

                if (!(bool)column.GetValue(HeaderSavedProperty))
                {
                    column.SetValue(OriginalHeaderProperty, header);
                    column.SetValue(HeaderSavedProperty, true);
                }

                if (column.GetValue(OriginalHeaderProperty) is not string original
                    || original.Length == 0)
                {
                    continue;
                }

                column.Header = column.SortDirection switch
                {
                    ListSortDirection.Ascending => original + AscendingArrow,
                    ListSortDirection.Descending => original + DescendingArrow,
                    _ => original
                };
            }
        }

        /// <summary>Размечает пути сортировки у всех колонок таблицы.</summary>
        private static void ConfigureColumns(DataGrid grid)
        {
            foreach (var column in grid.Columns)
            {
                string? path = ResolveSortPath(grid, column);
                if (string.IsNullOrWhiteSpace(path))
                {
                    // Колонка без привязки к данным (например, кнопки «Действия») — сортировать нечем.
                    column.CanUserSort = false;
                    continue;
                }

                column.CanUserSort = true;
                if (string.IsNullOrEmpty(column.SortMemberPath))
                    column.SortMemberPath = path;
            }
        }

        /// <summary>Определяет путь сортировки колонки или возвращает null, если сортировать нечем.</summary>
        private static string? ResolveSortPath(DataGrid grid, DataGridColumn column)
        {
            if (!string.IsNullOrEmpty(column.SortMemberPath))
                return column.SortMemberPath;

            if (column is DataGridBoundColumn bound && bound.Binding is Binding binding)
            {
                string? boundPath = binding.Path?.Path;
                return IsPathValid(grid, boundPath) ? boundPath : null;
            }

            if (column is DataGridTemplateColumn template)
            {
                string? templatePath = InferTemplatePath(template);
                return IsPathValid(grid, templatePath) ? templatePath : null;
            }

            return null;
        }

        /// <summary>
        /// Проверяет, что путь сортировки существует в текущем источнике данных: колонка таблицы
        /// данных (таблицы Белстата собраны в <see cref="DataView"/>) либо открытое свойство
        /// элемента коллекции.
        /// </summary>
        private static bool IsPathValid(DataGrid grid, string? path)
        {
            if (string.IsNullOrWhiteSpace(path)) return false;

            object? source = grid.ItemsSource;
            if (source is DataTable table)
                source = table.DefaultView;

            if (source is DataView view)
            {
                string name = UnwrapDataViewPath(path);
                return view.Table != null && view.Table.Columns.Contains(name);
            }

            var itemType = GetItemType(source);
            return itemType != null
                   && itemType.GetProperty(
                       path,
                       System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Instance) != null;
        }

        /// <summary>Снимает индексные скобки пути колонки таблицы данных: «[г. Минск]» → «г. Минск».</summary>
        private static string UnwrapDataViewPath(string path) =>
            path.Length > 2 && path[0] == '[' && path[^1] == ']'
                ? path.Substring(1, path.Length - 2)
                : path;

        /// <summary>Тип элемента источника данных (по обобщённому интерфейсу или по первому элементу).</summary>
        private static Type? GetItemType(object? source)
        {
            if (source == null) return null;

            var generic = source.GetType()
                .GetInterfaces()
                .FirstOrDefault(i => i.IsGenericType
                                     && i.GetGenericTypeDefinition() == typeof(IEnumerable<>)
                                     && i.GetGenericArguments()[0] != typeof(object));

            if (generic != null)
                return generic.GetGenericArguments()[0];

            if (source is IEnumerable enumerable)
            {
                foreach (var item in enumerable)
                    return item?.GetType();
            }

            return null;
        }

        /// <summary>Ищет путь сортировки в шаблоне ячейки: сначала привязка текста, затем любая привязка.</summary>
        private static string? InferTemplatePath(DataGridTemplateColumn column)
        {
            var template = column.CellTemplate;
            if (template == null) return null;

            FrameworkElement? root;
            try
            {
                root = template.LoadContent() as FrameworkElement;
            }
            catch (Exception)
            {
                // Шаблону нужны ресурсы, которых нет вне окна — колонка остаётся несортируемой.
                return null;
            }

            if (root == null) return null;

            return FindTextPath(root) ?? FindAnyPath(root);
        }

        /// <summary>Ищет привязку к <see cref="TextBlock.TextProperty"/> в дереве шаблона.</summary>
        private static string? FindTextPath(DependencyObject element)
        {
            if (element is TextBlock textBlock)
            {
                string? path = GetBindingPath(textBlock, TextBlock.TextProperty);
                if (!string.IsNullOrWhiteSpace(path)) return path;
            }

            foreach (var child in GetLogicalChildren(element))
            {
                string? path = FindTextPath(child);
                if (path != null) return path;
            }

            return null;
        }

        /// <summary>Ищет любую привязку в дереве шаблона (например, цвет плашки статуса).</summary>
        private static string? FindAnyPath(DependencyObject element)
        {
            foreach (var property in GetBoundProperties(element))
            {
                string? path = GetBindingPath(element, property);
                if (!string.IsNullOrWhiteSpace(path)) return path;
            }

            foreach (var child in GetLogicalChildren(element))
            {
                string? path = FindAnyPath(child);
                if (path != null) return path;
            }

            return null;
        }

        /// <summary>Свойства элемента, для которых локально задана привязка.</summary>
        private static IEnumerable<DependencyProperty> GetBoundProperties(DependencyObject element)
        {
            var enumerator = element.GetLocalValueEnumerator();
            while (enumerator.MoveNext())
            {
                var entry = enumerator.Current;
                if (entry.Value is BindingExpression || entry.Value is Binding)
                    yield return entry.Property;
            }
        }

        /// <summary>Путь привязки свойства или null, если привязки нет.</summary>
        private static string? GetBindingPath(DependencyObject element, DependencyProperty property) =>
            BindingOperations.GetBinding(element, property)?.Path?.Path;

        private static IEnumerable<DependencyObject> GetLogicalChildren(DependencyObject element)
        {
            foreach (var child in LogicalTreeHelper.GetChildren(element))
            {
                if (child is DependencyObject dependencyObject)
                    yield return dependencyObject;
            }
        }
    }
}
